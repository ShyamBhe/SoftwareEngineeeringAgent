from .. import llm
from ..tools import repo


def docs_writer(state):
    d = repo.diff(state["workdir"])
    readme = repo.read_file(state["workdir"], "README.md")
    section = llm.ask(
        "Write a concise README section (markdown) documenting the new feature: setup, env vars, "
        "endpoints, example curl commands. Output only the section.",
        f"Diff:\n{d}",
    )
    repo.write_file(state["workdir"], "README.md", readme.rstrip() + "\n\n" + section + "\n")
    return {"docs_summary": section[:500], "events": state["events"] + ["Docs updated"]}


def build_pr_body(state) -> str:
    t, rv, sec = state["test_result"], state["review"], state["security"]
    status = "✅ tests passing" if t["passed"] else "⚠️ tests FAILING after max fix attempts, needs human help"
    lines = [
        "## Summary",
        state["plan"]["goal"],
        "",
        "## Changes",
        *[f"- `{p}`" for p in sorted(set(state["changed_files"]))],
        "",
        "## Status",
        status,
        "",
        f"## AI review: {rv['verdict']}",
        rv["summary"],
        "",
        f"## Security risk: {sec['risk']}",
        *[f"- {x}" for x in sec["findings"]],
        "",
        "---",
        "*Generated by ai-swe-agent. Review before merging.*",
    ]
    return "\n".join(lines)


def pr_creator(state):
    body = build_pr_body(state)
    goal = state["plan"]["goal"]
    repo.commit_and_push(state["workdir"], state["branch"], f"feat: {goal[:60]}")
    url = repo.open_pr(state["repo_url"], state["branch"], f"[AI] {goal[:70]}", body)
    repo.cleanup(state["workdir"])
    return {"pr_url": url, "events": state["events"] + [f"PR opened: {url}"]}
